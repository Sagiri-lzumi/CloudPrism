package streaming

import "runtime"

// 明文内存保护。
//
// Python 版的明文片段（decrypt_range 的返回值）靠 GC 回收，何时清零
// 不可控；本包对流式解密的窗口缓冲做显式「写后清零」—— 这些缓冲可能
// 是文件级密钥流解出的整段视频数据，在进程内存中残留的时间越短越好
// （崩溃转储、事后内存取证、调试器都可能在残留窗口内读到明文）。
//
// 局限说明：Go 无法强制内存不被换出到磁盘、也无法保证栈/堆上所有
// 副本清零（string、逃逸分析由运行时决定），Scrub 是「尽力而为」的
// 纵深防御而非安全边界 —— 与 Python 相比已经是净增量（Python 完全
// 依赖 GC）。
//
// 清零对象：每个 256KiB 解密窗口缓冲（handler 写出后立即清零，
// 绝不进入 sync.Pool 复用 —— 池化会让同一块内存携带上一段明文被
// 下一段请求读到，属有意设计）。
func Scrub(b []byte) {
	for i := range b {
		b[i] = 0
	}
	// 防止未来编译器把上述清零判定为「死写」而优化掉
	runtime.KeepAlive(b)
}
